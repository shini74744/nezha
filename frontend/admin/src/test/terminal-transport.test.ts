import { beforeEach, afterEach, expect, test, vi } from "vitest"
beforeEach(() => vi.resetModules())
afterEach(() => vi.unstubAllGlobals())
test("TG HTTP stays on dedicated endpoint without cookies or admin fallback", async () => {
 const transport = await import("../lib/terminal-transport")
 const expired=vi.fn()
 const fetchMock=vi.fn().mockResolvedValue({ok:true,status:200,json:async()=>({success:true,data:[1]})})
 vi.stubGlobal("fetch",fetchMock)
 transport.setTelegramTerminalAccess({token:"private",ownerId:7,onExpired:expired})
 const {fetcher,FetcherMethod}=await import("../api/api")
 expect(await fetcher(FetcherMethod.GET,"/api/v1/terminal-commands")).toEqual([1])
 expect(fetchMock).toHaveBeenCalledTimes(1)
 expect(fetchMock.mock.calls[0][0]).toBe("/api/v1/telegram-terminal/ui")
 expect(fetchMock.mock.calls[0][1]).toMatchObject({method:"POST",credentials:"omit",cache:"no-store",redirect:"error"})
 expect(fetchMock.mock.calls[0][1].headers).not.toHaveProperty("X-CSRF-Token")
 fetchMock.mockResolvedValue({ok:false,status:403,json:async()=>({error:"expired"})})
 await expect(fetcher(FetcherMethod.GET,"/api/v1/terminal-commands")).rejects.toThrow("expired")
 expect(expired).toHaveBeenCalledOnce()
 await expect(fetcher(FetcherMethod.GET,"/api/v1/terminal-commands")).rejects.toThrow("授权")
 expect(fetchMock).toHaveBeenCalledTimes(2)
})
test("closing during asynchronous ticket request never opens a socket",async()=>{
 const transport=await import("../lib/terminal-transport")
 let finish:(value:unknown)=>void=()=>{}
 vi.stubGlobal("fetch",vi.fn(()=>new Promise(resolve=>{finish=resolve})))
 const ws=vi.fn()
 Object.assign(ws,{CONNECTING:0,OPEN:1,CLOSED:3})
 vi.stubGlobal("WebSocket",ws)
 transport.setTelegramTerminalAccess({token:"private",onExpired:()=>{}})
 const socket=transport.createTerminalSocket(new URL("https://example.test/api/v1/ws/terminal/one"))
 socket.close()
 finish({ok:true,status:200,json:async()=>({ticket:"one-use"})})
 await new Promise(resolve=>setTimeout(resolve,0))
 expect(ws).not.toHaveBeenCalled()
 expect(socket.readyState).toBe(3)
})
